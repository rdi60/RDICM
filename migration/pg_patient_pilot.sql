  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  patient_id BIGINT NOT NULL,
  visit_id BIGINT NOT NULL,
  treatment_number TEXT NOT NULL,
  tooth_number SMALLINT,
  description TEXT NOT NULL CHECK(length(description) BETWEEN 2 AND 500),
  planned_by BIGINT NOT NULL,
  performed_by BIGINT,
  status TEXT NOT NULL DEFAULT 'PLANNED' CHECK(status IN ('PLANNED','IN_PROGRESS','DONE','CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
