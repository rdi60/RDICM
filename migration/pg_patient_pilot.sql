CREATE TABLE rajan_pilot.invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  patient_id BIGINT NOT NULL,
  invoice_number TEXT NOT NULL,
  total NUMERIC(13,2) NOT NULL CHECK(total > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(entity_id,id), UNIQUE(entity_id,id,patient_id), UNIQUE(entity_id,invoice_number),
  FOREIGN KEY(entity_id,patient_id) REFERENCES rajan_pilot.patients(entity_id,id)
