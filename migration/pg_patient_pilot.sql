CREATE TABLE rajan_pilot.invoice_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL,
  patient_id BIGINT NOT NULL,
  invoice_id BIGINT NOT NULL,
