  UNIQUE(entity_id,id,patient_id),
  FOREIGN KEY(entity_id,patient_id) REFERENCES rajan_pilot.patients(entity_id,id),
  FOREIGN KEY(entity_id,visit_id) REFERENCES rajan_pilot.visits(entity_id,id),
  FOREIGN KEY(entity_id,planned_by) REFERENCES rajan_pilot.doctors(entity_id,id),
  FOREIGN KEY(entity_id,performed_by) REFERENCES rajan_pilot.doctors(entity_id,id)
);
