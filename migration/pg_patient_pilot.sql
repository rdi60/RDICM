CREATE TABLE rajan_pilot.receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  patient_id BIGINT NOT NULL,
  receipt_number TEXT NOT NULL,
  amount NUMERIC(13,2) NOT NULL CHECK(amount > 0),
  payment_mode TEXT NOT NULL CHECK(payment_mode IN ('CASH','UPI','CARD','BANK')),
  reference TEXT NOT NULL DEFAULT '',
  idempotency_key TEXT NOT NULL CHECK(length(idempotency_key) BETWEEN 8 AND 100),
  request_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(entity_id,id), UNIQUE(entity_id,id,patient_id), UNIQUE(entity_id,receipt_number),
  UNIQUE(entity_id,idempotency_key),
