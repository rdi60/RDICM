  amount NUMERIC(13,2) NOT NULL CHECK(amount > 0),
  UNIQUE(entity_id,treatment_id),
  FOREIGN KEY(entity_id,invoice_id,patient_id) REFERENCES rajan_pilot.invoices(entity_id,id,patient_id),
