-- DEVELOPMENT PILOT ONLY. Run as a separate provisioning role, in a disposable
-- PostgreSQL database with synthetic data. This is NOT the application schema.
-- The API role must NOT own these objects, be superuser, or have BYPASSRLS.
CREATE SCHEMA IF NOT EXISTS rajan_pilot;
CREATE TABLE rajan_pilot.entities (
  id BIGINT PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  CHECK (code ~ '^[A-Z][A-Z0-9]{1,11}$')
);
CREATE TABLE rajan_pilot.counters (
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  category TEXT NOT NULL CHECK (category IN ('TMP','UHID','VIS','APT','TRT','INV','RCP')),
  value BIGINT NOT NULL CHECK (value >= 0),
  PRIMARY KEY(entity_id,category)
);
CREATE TABLE rajan_pilot.patients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  uhid TEXT NOT NULL, name TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '',
  dob DATE, notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(entity_id,id), UNIQUE(entity_id,uhid)
);
CREATE TABLE rajan_pilot.registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  temp_id TEXT NOT NULL, name TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '',
  dob DATE, notes TEXT NOT NULL DEFAULT '', patient_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(entity_id,id), UNIQUE(entity_id,temp_id),
  FOREIGN KEY(entity_id,patient_id) REFERENCES rajan_pilot.patients(entity_id,id)
);
CREATE TABLE rajan_pilot.visits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  patient_id BIGINT NOT NULL,
  visit_number TEXT NOT NULL,
  chief_complaint TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(entity_id,id), UNIQUE(entity_id,visit_number),
  FOREIGN KEY(entity_id,patient_id) REFERENCES rajan_pilot.patients(entity_id,id)
);
-- PostgreSQL appointment pilot; btree_gist supports entity and doctor exclusion keys.
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE TABLE rajan_pilot.doctors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  display_name TEXT NOT NULL CHECK (length(display_name) BETWEEN 2 AND 120),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(entity_id,id)
);
CREATE TABLE rajan_pilot.resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  label TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('CHAIR','OT')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(entity_id,id), UNIQUE(entity_id,label)
);
CREATE TABLE rajan_pilot.doctor_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  weekday SMALLINT NOT NULL CHECK(weekday BETWEEN 0 AND 6),
  opens TIME NOT NULL, closes TIME NOT NULL,
  CHECK(opens < closes),
  FOREIGN KEY(entity_id,doctor_id) REFERENCES rajan_pilot.doctors(entity_id,id),
  UNIQUE(entity_id,doctor_id,weekday,opens,closes)
);
CREATE TABLE rajan_pilot.appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id BIGINT NOT NULL REFERENCES rajan_pilot.entities(id),
  patient_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  resource_id BIGINT NOT NULL,
  appointment_number TEXT NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'BOOKED'
    CHECK(status IN ('BOOKED','CONFIRMED','CHECKED_IN','IN_TREATMENT','COMPLETED','CANCELLED','NO_SHOW')),
  reason TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK(ends_at > starts_at),
  CHECK(ends_at <= starts_at + INTERVAL '4 hours'),
  UNIQUE(entity_id,id), UNIQUE(entity_id,appointment_number),
  FOREIGN KEY(entity_id,patient_id) REFERENCES rajan_pilot.patients(entity_id,id),
  FOREIGN KEY(entity_id,doctor_id) REFERENCES rajan_pilot.doctors(entity_id,id),
  FOREIGN KEY(entity_id,resource_id) REFERENCES rajan_pilot.resources(entity_id,id),
  CONSTRAINT appointment_doctor_conflict EXCLUDE USING gist (
    entity_id WITH =, doctor_id WITH =,
    tstzrange(starts_at,ends_at,'[)') WITH &&
  ) WHERE(status NOT IN ('CANCELLED','NO_SHOW')),
  CONSTRAINT appointment_resource_conflict EXCLUDE USING gist (
    entity_id WITH =, resource_id WITH =,
    tstzrange(starts_at,ends_at,'[)') WITH &&
  ) WHERE(status NOT IN ('CANCELLED','NO_SHOW'))
);
CREATE INDEX appointments_entity_start ON rajan_pilot.appointments(entity_id,starts_at);
CREATE INDEX appointments_patient_start ON rajan_pilot.appointments(entity_id,patient_id,starts_at);
CREATE INDEX visits_patient_latest ON rajan_pilot.visits(entity_id,patient_id,id DESC);
CREATE INDEX registrations_entity_latest ON rajan_pilot.registrations(entity_id,id DESC);
CREATE INDEX patients_entity_lookup ON rajan_pilot.patients(entity_id,name,phone);
