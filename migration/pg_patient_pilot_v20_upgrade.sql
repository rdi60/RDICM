  FOREIGN KEY(entity_id,receipt_id,patient_id) REFERENCES rajan_pilot.receipts(entity_id,id,patient_id),
  FOREIGN KEY(entity_id,invoice_id,patient_id) REFERENCES rajan_pilot.invoices(entity_id,id,patient_id)
);
-- The application locks each invoice before posting a receipt, but a direct
-- database user must not bypass this invariant. Recheck aggregate amounts
-- under invoice/receipt row locks via a constraint trigger.
CREATE FUNCTION rajan_pilot.check_allocation_totals() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER AS $$
DECLARE invoice_total NUMERIC(13,2); received NUMERIC(13,2);
BEGIN
 SELECT total INTO invoice_total FROM rajan_pilot.invoices
 WHERE entity_id=NEW.entity_id AND id=NEW.invoice_id FOR UPDATE;
 SELECT amount INTO received FROM rajan_pilot.receipts
 WHERE entity_id=NEW.entity_id AND id=NEW.receipt_id FOR UPDATE;
 IF (SELECT COALESCE(SUM(amount),0) FROM rajan_pilot.receipt_allocations
     WHERE entity_id=NEW.entity_id AND invoice_id=NEW.invoice_id) > invoice_total THEN
  RAISE EXCEPTION 'invoice over-allocation' USING ERRCODE='23514';
 END IF;
 IF (SELECT COALESCE(SUM(amount),0) FROM rajan_pilot.receipt_allocations
     WHERE entity_id=NEW.entity_id AND receipt_id=NEW.receipt_id) > received THEN
  RAISE EXCEPTION 'receipt over-allocation' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER allocation_limit_guard
 AFTER INSERT OR UPDATE ON rajan_pilot.receipt_allocations
 DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION rajan_pilot.check_allocation_totals();
DO $$ DECLARE t TEXT; BEGIN
 FOREACH t IN ARRAY ARRAY['treatments','invoices','invoice_items','receipts','receipt_allocations'] LOOP
  EXECUTE format('ALTER TABLE rajan_pilot.%I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('ALTER TABLE rajan_pilot.%I FORCE ROW LEVEL SECURITY',t);
  EXECUTE format('CREATE POLICY scoped_entity ON rajan_pilot.%I FOR ALL USING (entity_id = NULLIF(current_setting(''app.entity_id'',true),'''')::bigint) WITH CHECK (entity_id = NULLIF(current_setting(''app.entity_id'',true),'''')::bigint)',t);
 END LOOP;
END $$;
